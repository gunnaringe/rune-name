// Stored choice: "auto" (default), "nb", "nn", "is" or "en". Auto picks the first
// of those the browser prefers ("no" counts as Bokmål), and English otherwise.
function currentLang() {
    const stored = localStorage.getItem('lang');
    if (I18N[stored]) return stored;
    for (const l of navigator.languages || [navigator.language]) {
        const code = l.toLowerCase();
        if (code.startsWith('nn')) return 'nn';
        if (code.startsWith('nb') || code.startsWith('no')) return 'nb';
        if (code.startsWith('is')) return 'is';
        if (code.startsWith('en')) return 'en';
    }
    return 'en';
}

function t(key, vars) {
    let s = I18N[currentLang()][key] ?? I18N.en[key] ?? key;
    if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
    return s;
}

// Fills data-i18n (text), data-i18n-aria and data-i18n-placeholder, and sets
// <html lang> and the page title (from <html data-title>).
function applyI18n() {
    const root = document.documentElement;
    root.lang = currentLang();
    if (root.dataset.title) document.title = t(root.dataset.title);
    for (const e of document.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
    for (const e of document.querySelectorAll('[data-i18n-aria]')) e.setAttribute('aria-label', t(e.dataset.i18nAria));
    for (const e of document.querySelectorAll('[data-i18n-placeholder]')) e.placeholder = t(e.dataset.i18nPlaceholder);
}

addEventListener('storage', (e) => { if (e.key === 'lang') applyI18n(); });
